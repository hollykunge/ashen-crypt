    rows = {"idle": IDLE}
    for action, poses in [("walk", WALK), ("run", RUN), ("combat", COMBAT)]:
        rows.update({f"{action}-{i}": row for i, row in enumerate(poses)})
    return {
        name: [tuple(map(int, xy.split(","))) for xy in row.split()]
        for name, row in rows.items()
    }


